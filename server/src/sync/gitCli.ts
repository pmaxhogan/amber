const RATE_LIMITED = /rate limit|too many requests|\b429\b|retry-after|slow down/i;
const AUTH = new RegExp(
  [
    "authentication failed",
    "could not read username",
    "could not read password",
    "invalid username or password",
    "terminal prompts disabled",
    "\\b401\\b",
    "\\b403\\b",
    "permission denied",
    "access denied",
    "support for password authentication was removed",
    "bad credentials",
    "requested url returned error: 40[13]",
  ].join("|"),
  "i",
);
const NOT_FOUND = new RegExp(
  [
    "repository not found",
    "\\b404\\b",
    "does not appear to be a git repository",
    "not found: did you run git update-server-info",
    "remote: repository .* not found",
    "no such file or directory",
    "does not exist",
  ].join("|"),
  "i",
);
const NETWORK = new RegExp(
  [
    "could not resolve host",
    "couldn't resolve host",
    "connection refused",
    "connection timed out",
    "connection reset",
    "network is unreachable",
    "no route to host",
    "failed to connect",
    "unable to access",
    "ssl",
    "tls",
    "gnutls",
    "recv failure",
    "send failure",
    "empty reply from server",
    "early eof",
    "rpc failed",
    "the remote end hung up",
    "unexpected disconnect",
    "operation timed out",
    "proxy",
  ].join("|"),
  "i",
);
const DISK =
  /no space left on device|disk quota exceeded|cannot write|write error|read-only file system/i;
const TIMEOUT = /timed out|timeout/i;

/**
 * Map git stderr and exit codes onto the sync_runs.error_kind vocabulary.
 * Order matters: rate limiting looks like an auth failure, and "404" looks
 * like a network error once curl wraps it.
 */
export function classifyGitFailure(stderr: string, code: number, timedOut = false): SyncErrorKind {
  if (timedOut) {
    return "timeout";
  }
  const text = stderr;
  if (RATE_LIMITED.test(text)) {
    return "rate_limited";
  }
  if (AUTH.test(text)) {
    return "auth";
  }
  if (NOT_FOUND.test(text)) {
    return "not_found";
  }
  if (DISK.test(text)) {
    return "disk";
  }
  if (NETWORK.test(text)) {
    return "network";
  }
  if (TIMEOUT.test(text)) {
    return "timeout";
  }
  if (code !== 0) {
    return "git";
  }
  return "other";
}
